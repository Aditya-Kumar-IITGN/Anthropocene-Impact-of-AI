"""Write the data tables of the report as LaTeX fragments, straight from the CSVs (no hand-typed numbers).

Run:  /Users/aryan/miniforge3/envs/geo/bin/python -I report/analysis/make_tables.py
Inputs (read-only): presentation/data/processed/growth_table.csv (deck, growth_table.py)
                    report/data/d2_diagnostics.csv, d2_breaks.csv (d2_growth_diagnostics.py)
                    report/data/d3_country_table.csv, d3_gini.csv (d3_country_table.py)
Outputs: report/tables/growth.tex, breaks.tex, d3_country.tex (each is the tabular body only; the float, caption and
         label live in the section file, so text can be edited without touching numbers)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import DATA, PROC, REPORT  # noqa: E402

import pandas as pd  # noqa: E402

OUT = os.path.join(REPORT, "tables")
os.makedirs(OUT, exist_ok=True)


def w(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by report/analysis/make_tables.py -- do not edit by hand\n" + text.replace("\u2013", "--"))
    print("wrote tables/" + name)


def num(x, d=1):
    if pd.isna(x):
        return "--"
    if 0 < x < 0.5 * 10 ** -d:                    # would print as 0.0: show it as "<0.1" instead
        return f"$<${10 ** -d:.{d}f}"
    return f"{x:,.{d}f}"


# ------------------------------------------------------------------ growth table (D2)
g = pd.read_csv(os.path.join(PROC, "growth_table.csv"))
dg = pd.read_csv(os.path.join(DATA, "d2_diagnostics.csv"))
PH = {"Great Acceleration": r"\phGA{Great Acceleration}", "Cloud era": r"\phCloud{Cloud era}",
      "AI era": r"\phAI{AI era}"}
APPROX = {"Data-centre electricity, US"}           # LBNL rates are stated as approximate (~7, ~18 %/yr)
rows, last = [], None
for r in g.itertuples():
    ph = PH[r.phase] if r.phase != last else ""
    last = r.phase
    series = r.series.replace(" (reference)", "").replace(" (projected)", "")
    d = dg[(dg.series.str.startswith(r.series.split(",")[0].split(" (")[0])) & (dg.period == r.period)]
    if r.method.startswith("OLS"):
        ci = f"{r.T2_lo:.1f}--{r.T2_hi:.1f}" if r.T2 > 2 else f"{r.T2_lo:.2f}--{r.T2_hi:.2f}"
        hac = f"{d.T2_lo_hac.iloc[0]:.1f}--{d.T2_hi_hac.iloc[0]:.1f}" if len(d) and pd.notna(d.T2_lo_hac.iloc[0]) else "--"
        r2 = f"{d.r2.iloc[0]:.2f}" if len(d) else "--"
        basis = f"OLS, {r.n} {'years' if 'annual' in r.method else 'models'}"
    else:
        ci = hac = r2 = "--"
        basis = ("rate as stated (LBNL)" if r.series in APPROX else
                 "2 published values" + ("; projection" if r.projected else ""))
    ap = r"$\approx$" if r.series in APPROX else ""
    rr = f"{r.r_pct:.0f}" if r.r_pct > 100 else f"{r.r_pct:.1f}" if not ap else f"{r.r_pct:.0f}"
    t2 = f"{r.T2:.2f}" if r.T2 < 2 else f"{r.T2:.1f}" if r.T2 < 80 else f"{r.T2:.0f}"
    rows.append(f"{ph} & {series} & {r.period} & {ap}{rr} & {ap}{t2} & {ci} & {hac} & {r2} & {basis} \\\\")
w("growth.tex", "\n".join(rows) + "\n")

# ------------------------------------------------------------------ breakpoints
b = pd.read_csv(os.path.join(DATA, "d2_breaks.csv"))
rows = []
for r in b.itertuples():
    yr = f"{r.break_year:.0f}" if float(r.break_year).is_integer() else f"{r.break_year:.2f}"
    if pd.notna(r.T2_before):
        rate = f"$T_2$ {r.T2_before:.2f} $\\to$ {r.T2_after:.2f} yr"
    else:
        rate = f"{r.r_before_pct:.1f} $\\to$ {r.r_after_pct:.1f}\\,\\%/yr"
    name = "World energy" if r.series.startswith("World") else "AI compute"
    rows.append(f"{name} & {r.window} & {r.n} & {yr} & {rate} & ${r.delta_bic:.0f}$ \\\\")
w("breaks.tex", "\n".join(rows) + "\n")

# ------------------------------------------------------------------ D3 country table
t = pd.read_csv(os.path.join(DATA, "d3_country_table.csv"))
SHORT = {"United States": "United States", "United Arab Emirates": "UAE", "United Kingdom": "United Kingdom"}
rows = []
for r in t.itertuples():
    lq_now = "--" if r.mw_now == 0 else num(r.lq_now, 2 if r.lq_now < 1 else 1)
    rows.append(" & ".join([
        SHORT.get(r.country, r.country), f"{r.sites}", num(r.mw_now, 0), num(r.mw_2030, 0), num(r.share_2030_pct, 1),
        num(r.population_m, 1 if r.population_m < 100 else 0), lq_now, num(r.lq_2030, 2 if r.lq_2030 < 1 else 1),
        num(r.w_per_person_2030, 1), num(r.stressed_2030_pct, 0), num(r.people_50km_m, 1),
        f"{r.water_2030_low_bnL:,.0f}--{r.water_2030_high_bnL:,.0f}" if r.water_2030_low_bnL >= 1
        else f"{r.water_2030_low_bnL:.1f}--{r.water_2030_high_bnL:.1f}"]) + r" \\")
tot_now, tot_30 = t.mw_now.sum(), t.mw_2030.sum()
stressed_30 = (t.mw_2030 * t.stressed_2030_pct / 100).sum() / tot_30 * 100
gini = pd.read_csv(os.path.join(DATA, "d3_gini.csv"))
rows.append(r"\midrule")
rows.append(" & ".join([r"\textbf{All 12}", f"{t.sites.sum()}", num(tot_now, 0), num(tot_30, 0), "100.0",
                        num(t.population_m.sum(), 0), "", "", num(tot_30 * 1e6 / (t.population_m.sum() * 1e6), 1),
                        num(stressed_30, 0), "", f"{t.water_2030_low_bnL.sum():,.0f}--{t.water_2030_high_bnL.sum():,.0f}"
                        ]) + r" \\")
w("d3_country.tex", "\n".join(rows) + "\n")
print(f"check: total now {tot_now:,.0f} MW (deck 15,078); 2030 {tot_30:,.0f} (deck 50,324); "
      f"stressed 2030 share {stressed_30:.1f}% (deck 38.6)")
print(gini.round(3).to_string(index=False))
